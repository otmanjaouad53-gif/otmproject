int	ft_str_is_uppercase(char *str)
{
	int	i;

	i = 0;
	while (str[i]
		&& ((str[i] >= 'A' && str[i] <= 'Z')))
	{
		i++;
	}
	if (!str[i])
		return (1);
	return (0);
}
