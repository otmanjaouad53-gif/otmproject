int	ft_atoi(char *str)
{
	int	rs;
	int	sn;

	rs = 0;
	sn = 1;
	while (*str == 32 || (*str >= 9 && *str <= 13))
	{
		str++;
	}
	while (*str == '-' || *str == '+')
	{
		if (*str == '-')
			sn *= -1;
		str++;
	}
	while (*str >= '0' && *str <= '9')
	{
		rs = rs * 10 + *str - '0';
		str++;
	}
	return (rs * sn);
}
